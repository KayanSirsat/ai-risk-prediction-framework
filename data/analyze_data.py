import pandas as pd

df = pd.read_csv('data/ml_ready_data.csv')
print(f'Shape: {df.shape}')
print(f'Columns: {list(df.columns)}')
print(f'\nRisk Level distribution:')
print(df['Risk_Level'].value_counts())
print(f'\nClass proportions:')
print(df['Risk_Level'].value_counts(normalize=True).round(3))
print(f'\nNumerical columns:')
num = df.select_dtypes(include='number')
print(num.columns.tolist())
print(f'\nObject columns:')
obj = df.select_dtypes(include='object')
print(obj.columns.tolist())
print(f'\nMissing values per column:')
missing = df.isnull().sum()
print(missing[missing > 0])
print(f'\nDuplicate rows: {df.duplicated().sum()}')
print(f'\nActual_Days stats:')
print(df['Actual_Days'].describe())
print(f'\nCost_Consumed stats:')
print(df['Cost_Consumed'].describe())
print(f'\nBudget_Allocated stats:')
print(df['Budget_Allocated'].describe())
print(f'\nFirst 3 rows:')
print(df.head(3).to_string())